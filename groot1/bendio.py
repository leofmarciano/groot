"""Bridge between the PyTorch checkpoint and the Bend engine.

* `write_layout(header, path)` — compiles the .gbw tensor table into a Bend
  module (`layout.bend`) of constant defs: offsets (in floats) of every
  weight inside the single flat weights array, plus the model dimensions.
  Bend then needs no JSON parsing: `import ./layout.bend as L` and `L.wqkv(3)`.
* `load_gbw(path)` — numpy view of the data region (for hosts/tests).
* `RequestBlob` — the u32 request layout consumed by `bend/main.bend`:

      [0] n_chunks  [1] chunk_len_max  [2] n_questions  [3] n_options_total
      [4] opt_len_max  [5..] per-chunk lengths (n_chunks)
      then per-question: qtype, n_options
      then chunk token ids (n_chunks x chunk_len_max, pad 0)
      then option token ids (n_options_total x opt_len_max, pad 0) with the
      [MASK] position of each option row stored in a trailing array (n_options_total)
"""
from __future__ import annotations

import json
import struct
from pathlib import Path

import numpy as np

from .export import MAGIC, read_gbw_header

IDENTITY = 0xFFFFFFFF


def _tensor_map(header: dict) -> dict[str, dict]:
    return {t["name"]: t for t in header["tensors"]}


def _u32(v: int) -> str:
    return str(int(v))


def _f32(v: float) -> str:
    s = repr(float(v))
    if "e" in s or "E" in s:
        s = f"{float(v):.10f}"
    if "." not in s:
        s += ".0"
    return s


def _indexed_def(name: str, offsets: list[int]) -> str:
    lines = [f"def {name}(i: U32) -> U32:", "  match i:"]
    for k, off in enumerate(offsets):
        lines += [f"    case {k}:", f"      {_u32(off)}"]
    lines += ["    case _:", f"      {_u32(IDENTITY)}"]
    return "\n".join(lines) + "\n"


def write_layout(header: dict, path: str | Path) -> Path:
    tm = _tensor_map(header)
    cfg, enc = header["config"], header["encoder_config"]
    off = lambda n: tm[n]["offset"] // 4 if n in tm else IDENTITY  # noqa: E731
    n_layers = sum(1 for n in tm if n.startswith("encoder.layers.") and n.endswith(".attn.Wqkv.weight"))
    n_fusion = sum(1 for n in tm if n.startswith("fusion.") and n.endswith(".attn.Wqkv.weight"))
    d = enc["hidden_size"]
    out = ["# GENERATED by groot1.bendio.write_layout — offsets (in F32 slots) inside the weights array", "import Base", ""]
    scalars_u32 = {
        "d": d,
        "heads": enc["num_attention_heads"],
        "dh": d // enc["num_attention_heads"],
        "inter": enc["intermediate_size"],
        "layers": n_layers,
        "vocab": tm["encoder.embeddings.tok_embeddings.weight"]["shape"][0],
        "window": enc.get("local_attention", 128) // 2,
        "global_every": 1 if header.get("layer_types") and all(t == "full_attention" for t in header["layer_types"])
        else enc.get("global_attn_every_n_layers", 3),
        "fusion_layers": n_fusion,
        "fusion_heads": cfg["fusion_heads"],
        "fusion_inter": cfg["fusion_intermediate"],
        "max_chunks": cfg["max_chunks"],
        "tree_levels": cfg["tree_levels"],
        "chunk_tokens": cfg["chunk_tokens"],
        "scorer_hidden": tm["scorer.1.weight"]["shape"][0],
        "conf_hidden": tm["conf_head.0.weight"]["shape"][0],
        "total_floats": sum(t["numel"] for t in header["tensors"]),
    }
    for k, v in scalars_u32.items():
        out.append(f"def {k}() -> U32:\n  {_u32(v)}\n")
    scalars_f32 = {
        "eps": enc.get("norm_eps", 1e-5),
        "theta": enc.get("global_rope_theta", 160000.0),
        "local_theta": enc.get("local_rope_theta", enc.get("global_rope_theta", 160000.0)),
        "fusion_theta": cfg["rope_theta"],
        "temp_choice": header["temperature"][0],
        "temp_score": header["temperature"][1],
        "temp_noul": header["temperature"][2],
    }
    for k, v in scalars_f32.items():
        out.append(f"def {k}() -> F32:\n  {_f32(v)}\n")
    simple = {
        "tok_emb": "encoder.embeddings.tok_embeddings.weight",
        "emb_norm": "encoder.embeddings.norm.weight",
        "final_norm": "encoder.final_norm.weight",
        "seg_emb": "seg_emb.weight",
        "qtype_emb": "qtype_emb.weight",
        "level_emb": "level_emb.weight",
        "tree_w": "tree.merge.weight",
        "tree_b": "tree.merge.bias",
        "tree_norm": "tree.norm.weight",
        "tree_level": "tree.level_emb.weight",
        "g_final_norm": "final_norm.weight",
        "sc_ln_w": "scorer.0.weight",
        "sc_ln_b": "scorer.0.bias",
        "sc_w1": "scorer.1.weight",
        "sc_b1": "scorer.1.bias",
        "sc_w2": "scorer.3.weight",
        "sc_b2": "scorer.3.bias",
        "conf_w1": "conf_head.0.weight",
        "conf_b1": "conf_head.0.bias",
        "conf_w2": "conf_head.2.weight",
        "conf_b2": "conf_head.2.bias",
    }
    for k, n in simple.items():
        out.append(f"def {k}() -> U32:\n  {_u32(off(n))}\n")
    per_layer = {
        "attn_norm": "encoder.layers.{i}.attn_norm.weight",
        "wqkv": "encoder.layers.{i}.attn.Wqkv.weight",
        "wo": "encoder.layers.{i}.attn.Wo.weight",
        "mlp_norm": "encoder.layers.{i}.mlp_norm.weight",
        "wi": "encoder.layers.{i}.mlp.Wi.weight",
        "wmo": "encoder.layers.{i}.mlp.Wo.weight",
    }
    for k, pat in per_layer.items():
        out.append(_indexed_def(k, [off(pat.format(i=i)) for i in range(n_layers)]))
    per_fusion = {
        "f_attn_norm": "fusion.{i}.attn_norm.weight",
        "f_wqkv": "fusion.{i}.attn.Wqkv.weight",
        "f_wo": "fusion.{i}.attn.Wo.weight",
        "f_cross_norm": "fusion.{i}.cross_norm.weight",
        "f_wq": "fusion.{i}.cross.Wq.weight",
        "f_wkv": "fusion.{i}.cross.Wkv.weight",
        "f_cwo": "fusion.{i}.cross.Wo.weight",
        "f_mlp_norm": "fusion.{i}.mlp_norm.weight",
        "f_wi": "fusion.{i}.mlp.Wi.weight",
        "f_wmo": "fusion.{i}.mlp.Wo.weight",
    }
    for k, pat in per_fusion.items():
        out.append(_indexed_def(k, [off(pat.format(i=i)) for i in range(n_fusion)]))
    path = Path(path)
    path.write_text("\n".join(out))
    return path


def load_gbw(path: str | Path) -> tuple[dict, np.ndarray]:
    header = read_gbw_header(path)
    raw = Path(path).read_bytes()
    hlen = struct.unpack("<I", raw[4:8])[0]
    pad = (-(8 + hlen)) % 64
    data = np.frombuffer(raw, dtype="<f4", offset=8 + hlen + pad)
    return header, data


def data_offset(path: str | Path) -> int:
    raw = Path(path).read_bytes()[:8]
    assert raw[:4] == MAGIC
    hlen = struct.unpack("<I", raw[4:8])[0]
    return 8 + hlen + ((-(8 + hlen)) % 64)


class RequestBlob:
    """Flat u32 request for the Bend engine.

    header : n_chunks, chunk_len_max, n_questions, q_len_max, k_max, n_options
             chunk lengths (n_chunks)
             per question: qtype, K, L, first option index (4 words each)
    body   : chunk ids     (n_chunks x chunk_len_max)
             question ids  (n_questions x q_len_max)
             positions     (n_questions x q_len_max)
             blocks        (n_questions x q_len_max)
             markers       (n_questions x k_max)
    """

    @staticmethod
    def build(chunks: list[list[int]], questions: list) -> np.ndarray:
        nch, clen = len(chunks), max(len(c) for c in chunks)
        nq = len(questions)
        qlen = max(len(q.ids) for q in questions)
        kmax = max(q.n_options for q in questions)
        nopt = sum(q.n_options for q in questions)
        head = [nch, clen, nq, qlen, kmax, nopt] + [len(c) for c in chunks]
        o0 = 0
        for q in questions:
            head += [q.qtype, q.n_options, len(q.ids), o0]
            o0 += q.n_options
        pad = lambda xs, n: list(xs) + [0] * (n - len(xs))  # noqa: E731
        body: list[int] = []
        for c in chunks:
            body += pad(c, clen)
        for q in questions:
            body += pad(q.ids, qlen)
        for q in questions:
            body += pad(q.position_ids, qlen)
        for q in questions:
            body += pad(q.blocks, qlen)
        for q in questions:
            body += pad(q.markers, kmax)
        return np.array(head + body, dtype="<u4")

    @staticmethod
    def write(arr: np.ndarray, path: str | Path) -> int:
        Path(path).write_bytes(arr.tobytes())
        return int(arr.size)


def layout_from_gbw(gbw: str | Path, out: str | Path) -> Path:
    return write_layout(read_gbw_header(gbw), out)
